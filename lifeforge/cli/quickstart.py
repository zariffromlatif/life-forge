def add_quickstart_parser(subparsers: argparse._SubParsersAction) -> argparse.ArgumentParser:
    """Register the ``quickstart`` subcommand and return its parser."""
    parser = subparsers.add_parser(
        "quickstart",
        help="Auto-detect an agent framework, generate a harness, and evaluate it",
        description=(
            "Scan a directory for a supported agent framework, generate "
            "lifeforge_harness.py around the detected agent, and run the LIFE FORGE "
            "evolutionary evaluation."
        ),
    )
    parser.add_argument(
        "--path",
        type=str,
        default=".",
        help="Directory to scan for agent frameworks (default: current directory)",
    )
    parser.add_argument(
        "--dry-run",
        action="store_true",
        help="Detect and report only; write no harness and run no evaluation",
    )
    parser.add_argument(
        "--force",
        action="store_true",
        help="Overwrite an existing lifeforge_harness.py",
    )
    parser.add_argument(
        "--scenarios",
        type=int,
        default=30,
        help="Number of evolutionary generations (default: 30)",
    )
    parser.add_argument(
        "--seed",
        type=int,
        default=42,
        help="Random seed for deterministic exploration (default: 42)",
    )
    parser.add_argument(
        "--out",
        type=str,
        default="results/eval_report.md",
        help="Output markdown report path",
    )
    parser.add_argument(
        "--yes",
        action="store_true",
        help="Consent to importing and executing the detected agent file (required to evaluate)",
    )
    parser.set_defaults(func=cmd_quickstart)
    return parser


def cmd_quickstart(args: argparse.Namespace) -> int:
    """CLI entry point: run the quickstart flow from parsed arguments."""
    return run_quickstart(
        Path(getattr(args, "path", ".") or "."),
        dry_run=bool(getattr(args, "dry_run", False)),
        force=bool(getattr(args, "force", False)),
        scenarios=int(getattr(args, "scenarios", 30)),
        seed=int(getattr(args, "seed", 42)),
        out=str(getattr(args, "out", "results/eval_report.md")),
        yes=bool(getattr(args, "yes", False)),
    )
