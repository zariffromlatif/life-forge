"""Engagement kit: what an audit leaves behind besides the report.

An audit is worth more when the customer can keep using its results. After a
live audit run, :func:`write_regression_kit` saves

* ``regression_baseline.json`` - the failure surface plus the replayable
  regression corpus (every scenario the search kept, with the verdict), and
* ``ci/lifeforge-gate.yml`` - a ready-to-commit GitHub workflow that replays
  that corpus on every pull request and fails on regressions,

and :func:`write_security_review_answers` drafts plain-language answers to the
questions enterprise security reviews now ask about agents, built only from
the evidence in the report. Anything the evidence cannot answer is left as an
explicit TODO rather than guessed.
"""
from __future__ import annotations

from importlib import metadata
from pathlib import Path
from typing import Any

from lifeforge.hardening import _VIOLATION_SEVERITY
from lifeforge.reporting.audit import validity_warning
from lifeforge.reporting.failure_surface import capture_surface, save_surface
from lifeforge.reporting.regression_corpus import build_corpus

BASELINE_FILE = "regression_baseline.json"
WORKFLOW_FILE = "ci/lifeforge-gate.yml"
ANSWERS_FILE = "security_review_answers.md"


def _package_version() -> str:
    try:
        return metadata.version("lifeforge")
    except metadata.PackageNotFoundError:  # pragma: no cover - source checkout without install
        return "0.4.3"


def _yaml_scalar(value: Any) -> str:
    """Quote a value for a YAML workflow file (JSON strings are valid YAML)."""
    import json

    return json.dumps(str(value))


def _repo_relative_spec(spec: str | None, *, has_attr: bool) -> tuple[str | None, bool]:
    """Make a path (or ``path:attr`` target spec) relative to the working directory.

    CI runs from the repository root, so an absolute local path would break the
    workflow.  Returns ``(spec, needs_review)``.
    """
    if not spec:
        return spec, False
    path_part, attr = spec, ""
    if has_attr and ":" in spec:
        path_part, _, attr = spec.rpartition(":")
    candidate = Path(path_part)
    if not candidate.is_absolute():
        return spec, False
    try:
        relative = candidate.resolve().relative_to(Path.cwd().resolve())
    except ValueError:
        return spec, True
    return relative.as_posix() + (f":{attr}" if attr else ""), False


def render_gate_workflow(
    *,
    target: str | None,
    endpoint: str | None,
    domain_spec: str | None,
    domain: str | None,
    scenarios: int,
    seed: int,
    frontier: bool,
    baseline_path: str = f"lifeforge/{BASELINE_FILE}",
    reset_endpoint: str | None = None,
) -> str:
    """Render the GitHub workflow that replays the corpus on every PR."""
    target, target_review = _repo_relative_spec(target, has_attr=True)
    domain_spec, spec_review = _repo_relative_spec(domain_spec, has_attr=False)
    lines = [
        "# Agent regression gate generated by `lifeforge audit`.",
        f"# Commit {baseline_path} next to this workflow (as .github/workflows/lifeforge-gate.yml).",
        "# Every pull request replays the recorded scenarios against the changed agent and fails",
        "# when a previously handled scenario regresses. Re-record the baseline after intended changes:",
        "#   lifeforge surface --record ... --out " + baseline_path,
        *(
            ["# TODO: the agent/spec paths below were absolute on the audit machine; make them repo-relative."]
            if target_review or spec_review
            else []
        ),
        "name: Agent regression gate",
        "on: [pull_request]",
        "permissions:",
        "  contents: read",
        "  pull-requests: write",
        "jobs:",
        "  lifeforge-gate:",
        "    runs-on: ubuntu-latest",
        "    steps:",
        "      - uses: actions/checkout@v4",
        f"      - uses: zariffromlatif/life-forge@v{_package_version()}",
        "        with:",
        "          mode: surface",
        f"          surface-baseline: {_yaml_scalar(baseline_path)}",
    ]
    if target:
        lines.append(f"          surface-agent-target: {_yaml_scalar(target)}")
    elif endpoint:
        lines.append(f"          surface-endpoint: {_yaml_scalar(endpoint)}")
        if reset_endpoint:
            lines.append(f"          reset-endpoint: {_yaml_scalar(reset_endpoint)}")
    if domain_spec:
        lines.append(f"          domain-spec: {_yaml_scalar(domain_spec)}")
    elif domain:
        lines.append(f"          domain: {_yaml_scalar(domain)}")
    lines += [
        f"          scenarios: {_yaml_scalar(scenarios)}",
        f"          seed: {_yaml_scalar(seed)}",
        f"          frontier: {_yaml_scalar('true' if frontier else 'false')}",
        '          surface-fail-on-regression: "true"',
        "          # Sampled LLM agents: uncomment to replay each scenario 5x with tolerance.",
        '          # surface-repeats: "5"',
        '          # surface-tolerance: "0.2"',
    ]
    return "\n".join(lines) + "\n"


def write_regression_kit(
    out_dir: Path | str,
    summary: Any,
    agent: Any,
    runner: Any,
    *,
    target: str | None = None,
    endpoint: str | None = None,
    domain_spec: str | None = None,
    domain: str | None = None,
    scenarios: int = 30,
    seed: int = 42,
    frontier: bool = False,
    repeats: int = 1,
    reset_endpoint: str | None = None,
) -> dict[str, Path]:
    """Save the regression baseline (surface + corpus) and the CI workflow."""
    out = Path(out_dir)
    snapshot = capture_surface(
        summary,
        agent_name=getattr(agent, "name", type(agent).__name__),
        seed=seed,
        generations=scenarios,
        domain=domain,
        label="audit baseline",
    )
    # Every failing simulation goes into the corpus, not only the elite kept per cell,
    # so the gate replays each failure the audit found.
    seen: set[int] = set()
    scenarios = []
    for elite in [*summary.elites, *(getattr(summary, "failures", None) or [])]:
        if id(elite.trace) not in seen:
            seen.add(id(elite.trace))
            scenarios.append(elite)
    snapshot["corpus"] = build_corpus(
        scenarios, agent, runner, repeats=repeats, agent_name=snapshot["agent_name"], domain=domain
    )
    baseline = save_surface(snapshot, out / BASELINE_FILE)

    workflow = out / WORKFLOW_FILE
    workflow.parent.mkdir(parents=True, exist_ok=True)
    workflow.write_text(
        render_gate_workflow(
            target=target,
            endpoint=endpoint,
            domain_spec=domain_spec,
            domain=domain,
            scenarios=scenarios,
            seed=seed,
            frontier=frontier,
            reset_endpoint=reset_endpoint,
        ),
        encoding="utf-8",
    )
    return {"regression_baseline": baseline, "ci_workflow": workflow}


def _severity_counts(breakdown: dict[str, int]) -> dict[str, int]:
    counts = {"CRITICAL": 0, "HIGH": 0, "MEDIUM": 0, "LOW": 0}
    for category, count in breakdown.items():
        severity = _VIOLATION_SEVERITY.get(str(category).upper(), "MEDIUM")
        counts[severity] = counts.get(severity, 0) + int(count)
    return counts


def render_security_review_answers(
    report: dict[str, Any],
    *,
    customer: str | None = None,
    approval_gated_tools: list[str] | None = None,
    has_regression_gate: bool = False,
) -> str:
    """Draft answers to common enterprise AI-agent security-review questions.

    Every sentence is derived from the report; gaps are explicit TODOs. This is
    a drafting aid for the customer's security team, not an attestation.
    """
    breakdown = report.get("violation_breakdown") or report.get("failure_mode_breakdown") or {}
    severities = _severity_counts(breakdown)
    evaluations = report.get("total_evaluations") or report.get("scenarios_generated") or 0
    evaluations -= report.get("invalid_evaluations") or 0  # the agent failed to respond: not evaluated
    seed = report.get("seed")
    generations = report.get("generations")
    eval_rate = report.get("evaluation_failure_rate")
    agent = report.get("agent_name") or "the agent"
    subject = f"{customer} tests" if customer else "We test"

    def category_lines() -> list[str]:
        if not breakdown:
            return ["- No violations were recorded in the evaluated scenarios."]
        ordered = sorted(
            breakdown.items(),
            key=lambda item: ({"CRITICAL": 0, "HIGH": 1, "MEDIUM": 2, "LOW": 3}.get(
                _VIOLATION_SEVERITY.get(str(item[0]).upper(), "MEDIUM"), 4), str(item[0])),
        )
        return [
            f"- `{name}` ({_VIOLATION_SEVERITY.get(str(name).upper(), 'MEDIUM')}): observed in {count} scenario cell(s)"
            for name, count in ordered
        ]

    lines = [
        f"# Security Review Answers: {agent}",
        "",
        "> Draft answers to questions enterprise security reviews commonly ask about AI agents, generated "
        "from the attached LIFE FORGE audit evidence. Review and edit before sending. This is a "
        "point-in-time testing record, not a certification or a guarantee. Items marked **TODO** "
        "cannot be answered from testing evidence and must be completed by your team.",
        "",
        *validity_warning(report),
        "## How do you test the agent against prompt injection and unauthorized actions?",
        "",
        f"{subject} {agent} in a deterministic simulation of the tools it can call. An automated search "
        "generates adversarial and environmental scenarios (indirect prompt injection in tool data and "
        "messages, spoofed authority, conflicting instructions, price/stock volatility and resource "
        "pressure) and a rule-based oracle judges each episode by its effects on the simulated systems "
        "(money moved, records changed, messages sent, gated actions taken), not by the model's text.",
        "",
        f"- Scenarios evaluated in this audit: **{evaluations}**"
        + (f" ({generations} search generations, seed {seed}; the scenario set is reproducible, a sampled model's responses vary between runs)" if generations and seed is not None else ""),
    ]
    if eval_rate is not None:
        lines.append(f"- Share of evaluated scenarios with at least one violation: **{float(eval_rate):.1f}%**")
    lines += [
        "",
        "## What did testing find?",
        "",
        f"Findings by severity: **{severities['CRITICAL']} critical / {severities['HIGH']} high / "
        f"{severities['MEDIUM']} medium / {severities['LOW']} low** (counted per failing simulation).",
        "",
        *category_lines(),
        "",
        "Remediation status: **TODO** - state which findings were fixed and when the re-test passed.",
        "",
        "## Which actions require human approval?",
        "",
    ]
    if approval_gated_tools:
        lines.append(
            "The test environment enforces approval before these state-changing actions, and testing checks "
            "that the agent requests it first: " + ", ".join(f"`{tool}`" for tool in approval_gated_tools) + "."
        )
    else:
        lines.append("**TODO** - list the actions that require approval in production and where approvals are recorded.")
    lines += [
        "",
        "## How do you make sure a release does not reintroduce a fixed problem?",
        "",
    ]
    if has_regression_gate:
        lines.append(
            "Every scenario from this audit is stored as a regression corpus and replayed against each pull "
            "request in CI. A change that makes the agent fail a scenario it previously handled fails the "
            "build. For sampled models, each scenario is replayed several times and compared by failure rate."
        )
    else:
        lines.append("**TODO** - describe the regression testing in your release process.")
    lines += [
        "",
        "## Is adversarial testing recurring?",
        "",
        "Regression replay runs on every pull request; a full adversarial search should be re-run at least "
        "quarterly and after any change to the agent's tools or model. **TODO** - confirm your cadence.",
        "",
        "## Are agent actions logged and attributable?",
        "",
        "**TODO** - describe production action logging (what is logged, retention, tamper evidence). "
        "If you use the LIFE FORGE PolicyGateway, its hash-chained audit trail can be cited here.",
        "",
    ]
    return "\n".join(lines)


def write_security_review_answers(
    report: dict[str, Any],
    out_dir: Path | str,
    **kwargs: Any,
) -> Path:
    """Write :func:`render_security_review_answers` to the audit directory."""
    path = Path(out_dir) / ANSWERS_FILE
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(render_security_review_answers(report, **kwargs), encoding="utf-8")
    return path
