FRONTIER_MUTATORS: tuple[type[ScenarioMutator], ...] = (
    SelfReplicatingWormMutator,
    MemoryPoisoningMutator,
    CrossSessionPropagationMutator,
    ContextFloodMutator,
    MultilingualDegradationMutator,
)


def build_frontier_mutators() -> list[ScenarioMutator]:
    """Instantiate the full frontier attack set."""
    return [mutator_cls() for mutator_cls in FRONTIER_MUTATORS]
